// =========================
// LOW LEVEL I2C
// =========================
static void oled_write_cmd(uint8_t cmd)
{
    uint8_t buf[2] = {0x00, cmd};
    i2c_write_blocking(OLED_I2C, OLED_ADDR, buf, 2, false);
}

static void oled_write_data(const uint8_t *data, size_t len)
{
    uint8_t temp[17];
    temp[0] = 0x40;

    while (len)
    {
        size_t chunk = (len > 16) ? 16 : len;
        memcpy(&temp[1], data, chunk);
        i2c_write_blocking(OLED_I2C, OLED_ADDR, temp, chunk + 1, false);
        data += chunk;
        len -= chunk;
    }
}

static void oled_set_cursor(int col, int page)
{
    oled_write_cmd(0xB0 | (page & 0x07));
    oled_write_cmd(0x00 | (col & 0x0F));
    oled_write_cmd(0x10 | ((col >> 4) & 0x0F));
}

// =========================
// DRAWING
// =========================
static void oled_draw_char(int x, int page, char c)
{
    if (x > OLED_WIDTH - 6 || page >= OLED_PAGE_COUNT) return;

    if ((unsigned char)c < 32 || c > 126) c = '?';

    int offset = page * OLED_WIDTH + x;

    for (int i = 0; i < 5; i++)
        oled_buffer[offset + i] = font_ascii[c - 32][i];

    oled_buffer[offset + 5] = 0;
}

static void oled_draw_string(int x, int page, const char *text)
{
    while (*text && x <= OLED_WIDTH - 6)
    {
        oled_draw_char(x, page, *text++);
        x += 6;
    }
}

static void oled_clear(void)
{
    memset(oled_buffer, 0, sizeof(oled_buffer));
}

static void oled_update(void)
{
    for (int page = 0; page < OLED_PAGE_COUNT; page++)
    {
        oled_set_cursor(0, page);
        oled_write_data(&oled_buffer[page * OLED_WIDTH], OLED_WIDTH);
    }
}

// =========================
// INIT
// =========================
void oled_init(void)
{
    i2c_init(OLED_I2C, 400000);

    gpio_set_function(OLED_SDA_PIN, GPIO_FUNC_I2C);
    gpio_set_function(OLED_SCL_PIN, GPIO_FUNC_I2C);
    gpio_pull_up(OLED_SDA_PIN);
    gpio_pull_up(OLED_SCL_PIN);

    sleep_ms(100);

    oled_write_cmd(0xAE);
    oled_write_cmd(0x20); oled_write_cmd(0x00);
    oled_write_cmd(0xB0);
    oled_write_cmd(0xC8);
    oled_write_cmd(0x00);
    oled_write_cmd(0x10);
    oled_write_cmd(0x40);
    oled_write_cmd(0x81); oled_write_cmd(0x7F);
    oled_write_cmd(0xA1);
    oled_write_cmd(0xA6);
    oled_write_cmd(0xA8); oled_write_cmd(0x3F);
    oled_write_cmd(0xA4);
    oled_write_cmd(0xD3); oled_write_cmd(0x00);
    oled_write_cmd(0xD5); oled_write_cmd(0x80);
    oled_write_cmd(0xD9); oled_write_cmd(0xF1);
    oled_write_cmd(0xDA); oled_write_cmd(0x12);
    oled_write_cmd(0xDB); oled_write_cmd(0x40);
    oled_write_cmd(0x8D); oled_write_cmd(0x14);
    oled_write_cmd(0xAF);

    oled_clear();
    oled_update();
}

// =========================
// INTERNAL HELPERS
// =========================
static const char *mode_string(void)
{
    if (PIO_PINS_STABLE & 0x01) return "PRELOAD";
    if (PIO_PINS_STABLE & 0x02) return "IN";
    if (PIO_PINS_STABLE & 0x04) return "OUT";

    if ((CONTROL_PINS_STABLE & 0x03) == 0x03) return "SETPTR";
    if (CONTROL_PINS_STABLE & 0x02) return "WRITE";
    if (CONTROL_PINS_STABLE & 0x01) return "READ";
    if (CONTROL_PINS_STABLE & 0x04) return "NEXT";
    if (CONTROL_PINS_STABLE & 0x08) return "BACK";

    return "IDLE";
}

static void line(int page, const char *fmt, ...)
{
    char buf[32];

    va_list args;
    va_start(args, fmt);
    vsnprintf(buf, sizeof(buf), fmt, args);
    va_end(args);

    oled_draw_string(0, page, buf);
}

static void oled_draw_border(void)
{
    // top row: page 0, bit 0
    for (int x = 0; x < OLED_WIDTH; x++) {
        oled_buffer[x] |= 0x01;
    }

    // bottom row: page 7, bit 7
    for (int x = 0; x < OLED_WIDTH; x++) {
        oled_buffer[(OLED_PAGE_COUNT - 1) * OLED_WIDTH + x] |= 0x80;
    }

    // left and right columns: all pages, all bits
    for (int page = 0; page < OLED_PAGE_COUNT; page++) {
        oled_buffer[page * OLED_WIDTH + 0] |= 0xFF;
        oled_buffer[page * OLED_WIDTH + (OLED_WIDTH - 1)] |= 0xFF;
    }
}



// =========================
// THE ONLY PUBLIC DISPLAY
// =========================
void oled_print(void)
{

    oled_clear();
    oled_draw_border();

    line(1, " R:%d W:%d N:%d B:%d",
        !!(CONTROL_PINS_STABLE & 0x01),
        !!(CONTROL_PINS_STABLE & 0x02),
        !!(CONTROL_PINS_STABLE & 0x04),
        !!(CONTROL_PINS_STABLE & 0x08)
    );

    line(2, " PRE:%d IN:%d OUT:%d",
        !!(PIO_PINS_STABLE & 0x01),
        !!(PIO_PINS_STABLE & 0x02),
        !!(PIO_PINS_STABLE & 0x04)
    );

    line(3, " IN BUS: %u", IN_BUS_VALUE);

    line(4, " OUT BUS: %u", MEM_BUFFER[PTR]);

    line(5, "MODE:%s PTR:%u", mode_string(), PTR);

    line(6, " %u %u [%u] %u %u",
    MEM_BUFFER[(uint8_t)(PTR - 2)],
    MEM_BUFFER[(uint8_t)(PTR - 1)],
    MEM_BUFFER[PTR],
    MEM_BUFFER[(uint8_t)(PTR + 1)],
    MEM_BUFFER[(uint8_t)(PTR + 2)]
    );

    oled_update();
}